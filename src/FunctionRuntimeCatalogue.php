<?php

declare(strict_types=1);

namespace JDecool\ScalewayRuntime;

use Composer\Semver\VersionParser;

/**
 * The PHP version and the extensions measured on each supported Function Runtime, named and versioned as Composer sees
 * them there, generated from the probe's output (see docs/probe-results.md#function-runtime-catalogue).
 *
 * @phpstan-type FunctionRuntime array{measuredAt: string, php: string, extensions: array<string, string>}
 */
final readonly class FunctionRuntimeCatalogue
{
    public const string FILE = __DIR__.'/../resources/function-runtimes.php';

    /**
     * @param array<string, FunctionRuntime> $functionRuntimes by name, as "php84"
     */
    public function __construct(
        public array $functionRuntimes,
    ) {
    }

    public static function load(): self
    {
        /** @var array<string, FunctionRuntime> $functionRuntimes */
        $functionRuntimes = require self::FILE;

        return new self($functionRuntimes);
    }

    /**
     * @return FunctionRuntime
     */
    public function get(string $name): array
    {
        return $this->functionRuntimes[$name] ?? throw new \InvalidArgumentException(\sprintf('"%s" is not a measured Function Runtime: use %s.', $name, implode(' or ', array_keys($this->functionRuntimes))));
    }

    /**
     * Turns the outputs of the probe's "runtime" mode into the catalogue file. PHP and its extensions get the names and
     * versions of Composer's PlatformRepository, so that constraints are evaluated as Scaleway's "composer install" does.
     *
     * @param list<string> $probeOutputs
     */
    public static function generate(array $probeOutputs): string
    {
        $parser = new VersionParser();
        $functionRuntimes = [];
        foreach ($probeOutputs as $json) {
            $measurement = json_decode($json, true, 512, \JSON_THROW_ON_ERROR);
            if (!\is_array($measurement) || !\is_string($measuredAt = $measurement['measuredAt'] ?? null) || !\is_string($php = $measurement['phpVersion'] ?? null) || !\is_array($extensions = $measurement['extensions'] ?? null)) {
                throw new \UnexpectedValueException('A probe output must hold "measuredAt", "phpVersion" and "extensions".');
            }
            // Scaleway names its Function Runtimes after the PHP minor version.
            if (1 !== preg_match('/^(\d+)\.(\d+)\./', $php, $match)) {
                throw new \UnexpectedValueException(\sprintf('"%s" is not a PHP version.', $php));
            }
            $name = 'php'.$match[1].$match[2];
            if (isset($functionRuntimes[$name])) {
                throw new \UnexpectedValueException(\sprintf('Two probe outputs measure %s: keep one.', $name));
            }

            $versions = [];
            foreach ($extensions as $extension => $version) {
                // Composer does not register these two as packages.
                if (\in_array($extension, ['Core', 'standard'], true)) {
                    continue;
                }
                $versions['ext-'.str_replace(' ', '-', strtolower((string) $extension))] = self::composerVersion($parser, \is_string($version) ? $version : '0');
            }
            ksort($versions);

            $functionRuntimes[$name] = [
                'measuredAt' => $measuredAt,
                'php' => self::composerPhpVersion($parser, $php),
                'extensions' => $versions,
            ];
        }
        ksort($functionRuntimes);

        return "<?php\n\ndeclare(strict_types=1);\n\n// Generated by probe/catalogue.php from tests/Fixtures/FunctionRuntimes: do not edit by hand.\n\nreturn ".self::export($functionRuntimes, '').";\n";
    }

    /**
     * What changed since an older catalogue, one line each, for the pull request a new measurement opens.
     * Empty when only the measurement dates changed: the Function Runtimes still are as recorded.
     *
     * @return list<string>
     */
    public function changes(self $old): array
    {
        $changes = [];
        foreach (array_diff_key($old->functionRuntimes, $this->functionRuntimes) as $name => $_) {
            $changes[] = $name.': no longer measured';
        }
        foreach ($this->functionRuntimes as $name => $new) {
            $previous = $old->functionRuntimes[$name] ?? null;
            if (null === $previous) {
                $changes[] = \sprintf('%s: new Function Runtime, PHP %s with %d extensions', $name, $new['php'], \count($new['extensions']));
                continue;
            }
            $lines = $previous['php'] === $new['php'] ? [] : [\sprintf('%s: PHP %s -> %s', $name, $previous['php'], $new['php'])];
            foreach ($new['extensions'] + $previous['extensions'] as $extension => $_) {
                $before = $previous['extensions'][$extension] ?? null;
                $after = $new['extensions'][$extension] ?? null;
                $lines[] = match (true) {
                    null === $before => \sprintf('%s: + %s %s', $name, $extension, $after),
                    null === $after => \sprintf('%s: - %s', $name, $extension),
                    $before !== $after => \sprintf('%s: %s %s -> %s', $name, $extension, $before, $after),
                    default => null,
                };
            }
            $lines = array_values(array_filter($lines));
            if ([] !== $lines) {
                $changes = [...$changes, ...$lines, \sprintf('%s: measured %s -> %s', $name, $previous['measuredAt'], $new['measuredAt'])];
            }
        }

        return $changes;
    }

    /**
     * Composer keeps a parseable PHP_VERSION whole, so that "8.5.0-RC1" stays a pre-release, and cuts the others, as
     * "8.4.28-1+deb12", before their first "~", "+" or "-".
     */
    private static function composerPhpVersion(VersionParser $parser, string $version): string
    {
        try {
            $parser->normalize($version);

            return $version;
        } catch (\UnexpectedValueException) {
            return (string) preg_replace('/^([^~+-]+).*$/', '$1', $version);
        }
    }

    /**
     * Composer's fallback for a version it cannot parse, as "mysqlnd 8.4.28": its leading digits, or "0".
     */
    private static function composerVersion(VersionParser $parser, string $version): string
    {
        try {
            $parser->normalize($version);

            return $version;
        } catch (\UnexpectedValueException) {
            return 1 === preg_match('/^(\d+\.\d+\.\d+(?:\.\d+)?)/', $version, $match) ? $match[1] : '0';
        }
    }

    /**
     * @param array<mixed> $values
     */
    private static function export(array $values, string $indent): string
    {
        $lines = [];
        foreach ($values as $key => $value) {
            $lines[] = $indent.'    '.var_export($key, true).' => '.(\is_array($value) ? self::export($value, $indent.'    ') : var_export($value, true)).',';
        }

        return "[\n".implode("\n", $lines)."\n".$indent.']';
    }
}
